// Langue du coach (voix + texte des explications + notation des coups). Un
// seul réglage global, persistant, cyclé par un bouton (pas de menu déroulant).

const KEY = "echiquier_coach_lang";

export const LANGUAGES = [
  { code: "fr", flag: "🇫🇷", name: "Français", ttsLang: "fr-FR" },
  { code: "en", flag: "🇬🇧", name: "English", ttsLang: "en-US" },
  { code: "es", flag: "🇪🇸", name: "Español", ttsLang: "es-ES" },
  { code: "de", flag: "🇩🇪", name: "Deutsch", ttsLang: "de-DE" },
  { code: "it", flag: "🇮🇹", name: "Italiano", ttsLang: "it-IT" },
  { code: "pt", flag: "🇵🇹", name: "Português", ttsLang: "pt-PT" },
];

export function getCoachLang() {
  const saved = localStorage.getItem(KEY);
  return LANGUAGES.some((l) => l.code === saved) ? saved : "fr";
}

const listeners = [];
export function onCoachLangChange(cb) { listeners.push(cb); }

export function setCoachLang(code) {
  if (!LANGUAGES.some((l) => l.code === code)) return;
  localStorage.setItem(KEY, code);
  listeners.forEach((cb) => cb(code));
}

export function cycleCoachLang() {
  const codes = LANGUAGES.map((l) => l.code);
  const next = codes[(codes.indexOf(getCoachLang()) + 1) % codes.length];
  setCoachLang(next);
  return next;
}

export function ttsLangFor(code) {
  return (LANGUAGES.find((l) => l.code === code) || LANGUAGES[0]).ttsLang;
}

